# ตอน 96-100: ทุกย่อหน้าที่โนอาพูด "ปะป๊า" (ตรวจแล้วว่ามูนไม่ได้พูดในย่อหน้าเหล่านี้)
NOIA_PAPA = {96: [97, 112], 97: [19, 21, 24], 98: [9, 14, 20, 45, 51, 54], 100: [29]}
GLOBAL = [('ผู้ฆ่ามังกร', 'นักล่ามังกร'), ('เขตแดนมังกรเงิน', 'วิหารมังกรเงิน'), ('เขตแดน', 'วิหาร'),
          ('มะเขือม่วง', 'มะเขือยาว'), ('รูบิค', 'รูบิก'), ('รองอาจารย์ใหญ่', 'รองครูใหญ่'),
          ('“', '"'), ('”', '"'), ('(* ￣︿￣)', '(หน้ามุ่ย)'), ('(◕ᴗ◕✿)', '(ยิ้มแป้น)')]
GLOBAL_ONLY = {'เขตแดน': [111, 118]}   # "เขตแดน" เดี่ยวๆ = Sanctuary เฉพาะสองตอนนี้

for f in sorted(glob.glob('novels/dragon/chapters/ch*.json')):
    ch = json.load(open(f, encoding='utf-8')); n = ch['chapter']; P = ch['paragraphs']; old = list(P)
    for c, i, a, b in SPOT:
        if c == n:
            for k in ([i] if i is not None else range(len(P))):
                P[k] = P[k].replace(a, b)
    for k in NOIA_PAPA.get(n, []):
        P[k] = P[k].replace('ปะป๊า', 'ท่านพ่อ')
    for a, b in GLOBAL:
        if a in GLOBAL_ONLY and n not in GLOBAL_ONLY[a]:
            continue
        P[:] = [re.sub(r'  +', ' ', p.replace(a, b)).strip() for p in P]
    if n == 133:   # ต้นฉบับไม่มีตัดฉาก + เสียงตะโกนเพี้ยน
        P[:] = [p for k, p in enumerate(P) if not (p == '* * *' and k == 31)]
        P[:] = [p.replace('โอ้~ ม่าย！！ย！！', 'โอ้~ ม่ายยยย!!') for p in P]
    if P != old:
        for k, (x, y) in enumerate(zip(old, P)):
            if x != y: print(f'ch{n} [{k}] {x[:70]}\n      -> {y[:70]}')
        if len(P) != len(old): print(f'ch{n}: ย่อหน้า {len(old)} -> {len(P)}')
        json.dump(ch, open(f, 'w', encoding='utf-8'), ensure_ascii=False, indent=2)
