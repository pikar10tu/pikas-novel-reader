def clean_para(p):
    p = re.sub(r'&#8217;', "'", p)
    p = re.sub(r'&#8220;', '"', p)
    p = re.sub(r'&#8221;', '"', p)
    p = re.sub(r'&#8230;', '...', p)
    return p.strip()

